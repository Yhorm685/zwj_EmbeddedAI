"""Symmetric per-tensor int8 export and CMSIS-NN v7 double-rounding reference."""

import hashlib
import json
import math

import numpy as np

from .data import LABELS


def quantize(values, scale, low=-128):
    # PC and firmware explicitly use nearest-even float-to-int conversion.
    return np.clip(np.rint(np.asarray(values, np.float32) / np.float32(scale)),
                   low, 127).astype(np.int8)


def _scale(values):
    peak = float(np.max(np.abs(values)))
    if not math.isfinite(peak):
        raise ValueError("nonfinite calibration value")
    return float(np.float32(peak / 127)) if peak > 1e-12 else 1.0


def _multiplier(ratio):
    fraction, shift = math.frexp(ratio)
    m = int(math.floor(fraction * (1 << 31) + 0.5))
    if m == 1 << 31:
        m //= 2
        shift += 1
    if not -31 <= shift <= 30:
        raise ValueError(f"scale ratio outside CMSIS-NN shift range: {ratio}")
    return m, shift


def requantize(acc, multiplier, shift):
    """Match the v7 arm_nn_requantize default path, including negative ties."""
    acc = np.asarray(acc, dtype=np.int64) * (1 << max(shift, 0))
    if (acc < -(1 << 31)).any() or (acc >= (1 << 31)).any():
        raise OverflowError("int32 accumulator with left shift exceeds CMSIS-NN range")
    result = (acc * multiplier + (1 << 30)) >> 31
    right = max(-shift, 0)
    if right:
        result = np.sign(result) * ((np.abs(result) + (1 << (right - 1))) >> right)
    return result


def _layer(weights, bias, in_scale, out_scale):
    weight_scale = _scale(weights)
    w = quantize(weights, weight_scale, -127)
    bias_scale = float(in_scale) * weight_scale
    b = np.rint(bias.astype(np.float64) / bias_scale)
    if not np.isfinite(b).all() or (np.abs(b) >= 1 << 31).any():
        raise ValueError("bias cannot be represented safely in int32")
    m, shift = _multiplier(bias_scale / out_scale)
    # Every possible input vector (not only calibration examples) must be safe.
    bound = np.abs(w.astype(np.int64)).sum(axis=1) * 128 + np.abs(b)
    if np.max(bound) * (1 << max(shift, 0)) >= 1 << 31:
        raise ValueError("requantization may overflow int32")
    return {"w": w.tolist(), "b": b.astype(np.int32).tolist(), "weight_scale": weight_scale,
            "multiplier": m, "shift": shift}


def model_digest(model):
    body = {k: v for k, v in model.items() if k != "model_id"}
    compact = json.dumps(body, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(compact.encode("utf-8")).hexdigest()


def calibrate(mean, std, w1, b1, w2, b2, training_features, checkpoint_sha):
    z = (training_features - mean) / std
    hidden = np.maximum(z @ w1.T + b1, 0)
    logits = hidden @ w2.T + b2
    ins, hs, outs = (_scale(x) for x in (z, hidden, logits))
    model = {"format": 1, "checkpoint_sha256": checkpoint_sha, "class_order": list(LABELS),
             "feature_mean": mean.tolist(), "feature_std": std.tolist(),
             "input_scale": ins, "hidden_scale": hs, "output_scale": outs,
             "layer1": _layer(w1, b1, ins, hs), "layer2": _layer(w2, b2, hs, outs)}
    model["model_id"] = model_digest(model)
    return model


def quantized_features(feature_values, model):
    z = (feature_values - np.asarray(model["feature_mean"], np.float32))
    z /= np.asarray(model["feature_std"], np.float32)
    return quantize(z, model["input_scale"])


def predict_q(input_q, model):
    values = np.asarray(input_q, dtype=np.int64)
    for name, minimum in (("layer1", 0), ("layer2", -128)):
        layer = model[name]
        weights = np.asarray(layer["w"], dtype=np.int64)
        acc = values @ weights.T + np.asarray(layer["b"], dtype=np.int64)
        scaled = requantize(acc, layer["multiplier"], layer["shift"])
        values = np.clip(scaled, minimum, 127)
    return values.astype(np.int8)


def write_header(path, model):
    def f32(value):
        # Nine decimal digits round-trip binary32 and the decimal point makes C literals valid.
        return f"{float(value):.9e}f"

    lines = ["/* Generated by python -m ml.export. */", "#pragma once", "#include <stdint.h>",
             f'#define MOTION_MODEL_ID "{model["model_id"]}"']

    def array(ctype, name, values, formatter=str):
        flat = np.asarray(values).ravel()
        lines.append(f"static const {ctype} {name}[{len(flat)}] = {{")
        for i in range(0, len(flat), 8):
            lines.append("    " + ", ".join(formatter(x) for x in flat[i:i + 8]) + ",")
        lines.append("};")

    for name in ("feature_mean", "feature_std"):
        array("float", "motion_" + name, model[name], f32)
    for name in ("input_scale", "output_scale"):
        lines.append(f'static const float motion_{name} = {f32(model[name])};')
    for index in (1, 2):
        layer = model[f"layer{index}"]
        array("int8_t", f"motion_w{index}", layer["w"])
        array("int32_t", f"motion_b{index}", layer["b"])
        lines.append(f'static const int32_t motion_mult{index} = {layer["multiplier"]};')
        lines.append(f'static const int32_t motion_shift{index} = {layer["shift"]};')
    path.write_bytes(("\n".join(lines) + "\n").encode("ascii"))
